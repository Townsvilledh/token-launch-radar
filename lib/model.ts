// Token Radar's model, radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks EVERY pre-token protocol the snapshot can rank, not just the watchlist floor:
// the watchlist is covered in full, and every other rankable pre-token protocol joins it, so the
// radar's job is to find the early ones, not to re-list the 40 the house already named.
//
// A protocol is pre-token when its DefiLlama record carries no token (no market cap, no CoinGecko
// id, no symbol). That is a record, never a proof: the dashboard says "records no token", never
// "has no token". Live-token protocols are kept apart and shown with the market's own values.
// A wrapped, staked or bridged product of a token that already trades is never ranked, even when
// its record carries no token: WBTC is Bitcoin on Ethereum, not a launch waiting to happen. The
// field guide's watchlist rule (product categories, wrapped/staked words, exchange-name prefixes,
// version markers) is applied to every row, not just the watchlist.
//
// Implied value is derived from the snapshot's own figures, never from a hand-kept list of names:
//
//   peerMultiple  = the median market-cap / TVL of the LIVE-token protocols in the same category,
//                   computed from this snapshot at run time (at least 3 peers, else the live
//                   universe's own median), clamped to [0.05, 0.80]
//   growthMult    = 1 + clamp(change_7d, -60, 120) / 100 x 0.5
//   maturityMult  = 0.7 + 0.3 x min(age_days, 1095) / 1095   (age unknown: 365 days)
//   breadthMult   = 1 + 0.02 x min(chains - 1, 5)
//   implied       = max(1, round(tvl_usd x peerMultiple x growthMult x maturityMult x breadthMult))
//
// Why peers, not a flat multiple: a token's launch value is what the market already pays for the
// same kind of protocol. A lending protocol launches against lending multiples, a bridge against
// bridge multiples. The multiple is read off the live protocols in the same snapshot, so the same
// program run on a later snapshot re-prices every row from that snapshot's own market — the radar
// finds future launches early because it never hardcodes which names matter.
//
// No protocol name is ever special-cased: the same function scores every row.

