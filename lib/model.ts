const DAY_MS = 86_400_000;

/** A finite number, else `fallback`. */
function finite(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

/** A whole day count from `from` to `to`, clamped at zero; null when either date is absent or bad. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const a = Date.parse(`${asOf}T00:00:00Z`);
  const b = Date.parse(`${listedAt}T00:00:00Z`);
  if (!Number.isFinite(a) || !Number.isFinite(b)) return null;
  return Math.max(0, Math.floor((a - b) / DAY_MS));
}

/** The median of a sorted list of numbers; 0 when empty. */
export function median(sorted: number[]): number {
  if (sorted.length === 0) return 0;
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 1 ? sorted[mid]! : (sorted[mid - 1]! + sorted[mid]!) / 2;
}

/** Clamp `v` into [lo, hi]. */
function clamp(v: number, lo: number, hi: number): number {
  return Math.min(hi, Math.max(lo, v));
}

/** The live-token peers of every category: median market-cap / TVL, with examples. */
export function peerTable(snapshot: Snapshot, model: ModelConstants): { byCategory: Map<string, PeerStats>; universe: number } {
  const live = snapshot.protocols.filter(
    (p) => p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0 && p.category !== null,
  );
  const byCategory = new Map<string, PeerStats>();
  const byCat = new Map<string, { name: string; multiple: number }[]>();
  for (const p of live) {
    const list = byCat.get(p.category!) ?? [];
    list.push({ name: p.name, multiple: p.mcap_usd! / p.tvl_usd });
    byCat.set(p.category!, list);
  }
  const universe = clamp(
    median(live.map((p) => p.mcap_usd! / p.tvl_usd).sort((a, b) => a - b)),
    model.peer_multiple_floor,
    model.peer_multiple_cap,
  );
  for (const [category, peers] of byCat) {
    const multiples = peers.map((x) => x.multiple).sort((a, b) => a - b);
    const examples = [...peers]
      .sort((a, b) => b.multiple - a.multiple || (a.name < b.name ? -1 : 1))
      .slice(0, 3);
    byCategory.set(category, {
      category,
      count: peers.length,
      median_multiple: clamp(median(multiples), model.peer_multiple_floor, model.peer_multiple_cap),
      examples,
    });
  }
  return { byCategory, universe };
}

/** The peer multiple one protocol gets: its category's live median, else the universe median. */
export function peerMultipleFor(
  p: SnapshotProtocol,
  peers: { byCategory: Map<string, PeerStats>; universe: number },
  model: ModelConstants,
): { multiple: number; count: number; source: 'category' | 'universe' } {
  const stats = p.category === null ? undefined : peers.byCategory.get(p.category);
  if (stats !== undefined && stats.count >= model.peer_min_count) {
    return { multiple: stats.median_multiple, count: stats.count, source: 'category' };
  }
  return { multiple: peers.universe, count: 0, source: 'universe' };
}

/** The multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  peers: { byCategory: Map<string, PeerStats>; universe: number },
  model: ModelConstants,
): {
  implied: number;
  peer: { multiple: number; count: number; source: 'category' | 'universe' };
  growthPct: number;
  growthMult: number;
  maturityMult: number;
  breadthMult: number;
  age: number | null;
} {
  const age = ageDays(asOf, protocol.listed_at);
  const peer = peerMultipleFor(protocol, peers, model);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = clamp(rawGrowth, model.growth_floor, model.growth_cap);
  const growthMult = 1 + (growthPct / 100) * model.growth_weight;
  const ageForModel = age ?? model.unknown_age_days;
  const maturityMult =
    model.maturity_floor +
    (Math.min(Math.max(ageForModel, 0), model.maturity_days) / model.maturity_days) * model.maturity_range;
  const extraChains = Math.min(Math.max(protocol.chains.length - 1, 0), model.breadth_max_chains);
  const breadthMult = 1 + model.breadth_per_chain * extraChains;
  const implied = Math.max(1, Math.round(protocol.tvl_usd * peer.multiple * growthMult * maturityMult * breadthMult));
  return { implied, peer, growthPct, growthMult, maturityMult, breadthMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Categories the field guide counts as a wrapped, staked or bridged product of a token that
 *  already trades — a receipt for another token is not a token that does not exist yet. */
const PRODUCT_CATEGORIES = new Set([
  'Bridge',
  'Canonical Bridge',
  'Liquid Staking',
  'Liquid Restaking',
  'Restaked BTC',
  'CEX',
]);

/** Exchange names a protocol name must not begin with (the field guide's rule). */
const EXCHANGE_PREFIXES = ['Binance', 'Coinbase', 'Bybit', 'Kraken', 'Bitget', 'OKX', 'Bitfinex', 'Gemini'];

/** A whole word wrapped, staked or staking anywhere in a name. */
const WRAPPED_WORD = /\b(wrapped|staked|staking)\b/i;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/**
 * Whether a protocol is one the board may rank. The field guide's watchlist rule, applied to
 * every row, not just the watchlist: pre-token, not a wrapped, staked or bridged product of a
 * token that already trades (WBTC is Bitcoin on Ethereum, Binance staked ETH is ETH in a
 * staking product — neither is a protocol still waiting on a launch of its own), not an
 * exchange's own product, and not a versioned pool of another protocol. Without this, the
 * board's top rows would be bridges and wrapped tokens, and the radar would rank products
 * whose token already trades ahead of the launches it exists to find.
 */
export function isRankable(p: SnapshotProtocol): boolean {
  if (!isPreToken(p)) return false;
  if (p.category !== null && PRODUCT_CATEGORIES.has(p.category)) return false;
  if (WRAPPED_WORD.test(p.name)) return false;
  if (EXCHANGE_PREFIXES.some((e) => p.name.startsWith(e))) return false;
  if (VERSIONED.test(p.name)) return false;
  return true;
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** One line saying why a row ranks where it does, from its own figures. */
export function whyText(
  p: SnapshotProtocol,
  peer: { multiple: number; count: number; source: 'category' | 'universe' },
  growthPct: number,
  age: number | null,
): string {
  const tvl = p.tvl_usd >= 1e9 ? `$${(p.tvl_usd / 1e9).toFixed(1)}B TVL` : `$${Math.round(p.tvl_usd / 1e6)}M TVL`;
  const peerBit =
    peer.source === 'category'
      ? `peers in ${p.category ?? 'its category'} price at ${peer.multiple.toFixed(2)}x TVL (${peer.count} live)`
      : `too few live peers in ${p.category ?? 'its category'}, so the universe median ${peer.multiple.toFixed(2)}x TVL applies`;
  const growthBit =
    p.change_7d === null ? 'no 7-day change reported' : `7-day TVL ${growthPct >= 0 ? '+' : ''}${growthPct.toFixed(1)}%`;
  const ageBit = age === null ? 'age unknown' : age >= 365 ? `${(age / 365).toFixed(1)} years with no token on record` : `${age} days with no token on record`;
  return `${tvl}; ${peerBit}; ${growthBit}; ${ageBit}.`;
}

/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants = MODEL): BoardRow[] {
  const peers = peerTable(snapshot, model);
  const index = bySlug(snapshot.protocols);
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug it names is ranked, whatever its TVL.
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: every other rankable pre-token protocol, by TVL. No cap: the board ranks
  // the whole pre-token universe the snapshot can rank, so an early launch is never left out
  // because it sat below an arbitrary cut.
  const early = snapshot.protocols
    .filter((p) => !chosen.has(p.slug) && isRankable(p))
    .sort((a, b) => b.tvl_usd - a.tvl_usd || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0));
  for (const p of early) chosen.set(p.slug, p);

  const scored = [...chosen.values()].map((p) => {
    const v = impliedValue(p, snapshot.as_of, peers, model);
    return { p, v };
  });
  scored.sort((a, b) => b.v.implied - a.v.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    age_days: s.v.age,
    implied_value_usd: s.v.implied,
    // Full precision, never rounded: the dashboard recomputes every row from these numbers
    // and must land on the same implied value board.json carries, to the dollar.
    model: {
      peer_multiple: s.v.peer.multiple,
      peer_count: s.v.peer.count,
      peer_source: s.v.peer.source,
      growth_pct: s.v.growthPct,
      growth_multiplier: s.v.growthMult,
      maturity_multiplier: s.v.maturityMult,
      breadth_multiplier: s.v.breadthMult,
      age_days: s.v.age,
    },
    why: whyText(s.p, s.v.peer, s.v.growthPct, s.v.age),
    farm_steps: farmSteps(s.p, s.v.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  let s = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (s.length > 600) s = `${s.slice(0, 596)}...`;
  if (s.length < 20) s = `${s} Hold the position and check the protocol's own page.`;
  return s;
}

/** The first chain a protocol names, or a neutral phrase. */
function chainOf(p: SnapshotProtocol): string {
  return p.chains.length > 0 ? p.chains[0]! : 'its main chain';
}

/** How much capital one farm position needs, from the protocol's own TVL. */
function capitalFor(p: SnapshotProtocol): number {
  if (p.tvl_usd >= 5_000_000_000) return 250;
  if (p.tvl_usd >= 1_000_000_000) return 150;
  if (p.tvl_usd >= 100_000_000) return 100;
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  if (age < 180) return 60;
  if (age < 365) return 45;
  return 30;
}

/** The category's first action, in the words a farmer can follow. */
function actionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the position open.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm')) return `Provide $${capital} of liquidity to ${name}'s main pool on ${chain} and keep the position open.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('staking') || c.includes('restak')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Deposit $${capital} of USDC as margin on ${name} and open one small hedge.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('curator') || c.includes('allocator')) return `Deposit $${capital} into a ${name} vault on ${chain} and keep the shares.`;
  if (c.includes('stable')) return `Mint or deposit $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield asset on ${chain} and hold it.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  if (c.includes('basis')) return `Deposit $${capital} of USDC into ${name}'s basis vault on ${chain} and keep the position.`;
  if (c.includes('privacy')) return `Deposit $${capital} into ${name}'s shielded pool on ${chain} and keep the receipt.`;
  return `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`;
}

/** The category's second, weekly action: a different interaction from the first. */
function secondActionFor(p: SnapshotProtocol, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp')) return `Borrow a small amount against the supply on ${name} and repay it the same week.`;
  if (c.includes('dex') || c.includes('yield')) return `Swap a small amount through ${name} on ${chain} so the wallet shows trading activity.`;
  if (c.includes('bridge')) return `Bridge a small amount back through ${name} so the wallet shows use in both directions.`;
  if (c.includes('staking') || c.includes('restak')) return `Claim or restake the staking rewards on ${name} once a week.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Close the hedge and open a fresh one on ${name} so the wallet shows repeated use.`;
  if (c.includes('prediction')) return `Settle one market and place a fresh position on ${name}.`;
  if (c.includes('governance') || c.includes('dao')) return `Vote on one open proposal on ${name} when one is live.`;
  return `Use one more feature of ${name} on ${chain} each week, such as a swap, a vote or a claim.`;
}

/**
 * A protocol's farm plan: seven steps, each an action with a cost and a time. The plan is derived
 * from the protocol's own record (category, chains, TVL, age), never from a hand-written list of
 * names. Step 5 is the safety check every plan carries: verify the protocol's own links first and
 * never pay to claim.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const action = actionFor(p, capital, chain);
  const second = secondActionFor(p, chain);
  const others = p.chains.length > 1 ? ` Repeat the first position on ${p.chains[1]} too, since ${p.name} also runs there.` : '';
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: action,
      cost: `$${capital} of capital and about $${capital >= 150 ? 8 : 4} of gas`,
      time: '15 minutes to set up',
    },
    {
      text: `${second}${others}`,
      cost: 'about $2 of gas a week',
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you interact again, check that the app you open is the protocol's own page from its official links, and never pay a fee to claim an airdrop.`,
      cost: 'no fee to check',
      time: '5 minutes',
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.`,
      cost: 'nothing but the log',
      time: '5 minutes',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

